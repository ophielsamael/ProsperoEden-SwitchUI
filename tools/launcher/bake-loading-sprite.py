"""Writes headless/loading_sprite.glsl: the small pictures of the loading screen, from
headless/prosperoeden/ui/art, so the loading shader needs no texture in either graphics backend:

  the walker  walker_0/1.png: walks on the end of the progress bar, the two frames taking turns
  the marks   mark_busy_0/1.png, mark_done.png: beside each step; mark_busy_0 faint while the
              step waits, mark_busy_0 and _1 taking turns while it is under way, mark_done once
              it is done

Any picture can take a frame's place: RGBA with a transparent background, the figure's feet at
the bottom (128x128 works well). See docs/SWITCH-UI.md.

The frames of a set are cut to the part they draw on (one box for the whole set, so they do not
jump against each other), reduced to the set's size in texels and share one palette of 15 colours;
texel 0 is transparent. A texel takes four bits (eight per uint, lowest bits first, top row first),
as the lettering does (bake-loading-text.py). The frames are kept small on purpose: a console takes
about a millisecond per word to compile the shader.
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "headless/prosperoeden/ui/art"
OUTPUT = ROOT / "headless/loading_sprite.glsl"
COLOURS = 15
# name: (pictures, texels wide, texels high). The frames are numbered in this order.
SETS = {
    "Walker": (["walker_0", "walker_1"], 32, 48),
    "Mark": (["mark_busy_0", "mark_busy_1", "mark_done"], 26, 28),
}


def frames(names, width, height):
    images = [Image.open(ART / f"{name}.png").convert("RGBA") for name in names]
    boxes = [image.getchannel("A").getbbox() for image in images]
    left, top = min(box[0] for box in boxes), min(box[1] for box in boxes)
    right, bottom = max(box[2] for box in boxes), max(box[3] for box in boxes)
    # Widened (or narrowed) to the set's proportion, around the middle, the feet on the bottom row.
    cut = round((bottom - top) * width / height)
    left -= (cut - (right - left)) // 2
    box = (left, top, left + cut, bottom)
    # Reduced with the colour weighted by its cover, so the outline does not turn into a halo.
    return [image.crop(box).convert("RGBa").resize((width, height), Image.Resampling.LANCZOS).convert("RGBA")
            for image in images]


def bake(names, width, height):
    """The set's palette (r, g, b in 0..1) and each frame's words."""
    small = frames(names, width, height)
    # One palette for the set: quantize its frames side by side, over the texels that are drawn.
    sheet = Image.new("RGBA", (width * len(small), height))
    for index, frame in enumerate(small):
        sheet.paste(frame, (index * width, 0))
    shown = sheet.getchannel("A").point(lambda value: 255 if value >= 128 else 0)
    flat = Image.new("RGB", sheet.size)
    flat.paste(sheet.convert("RGB"), mask=shown)
    # Maximum coverage keeps the small bright parts (shoes, a shell's rim) that median cut merges
    # into the large ones.
    quantized = flat.quantize(COLOURS, method=Image.Quantize.MAXCOVERAGE, dither=Image.Dither.NONE)
    palette = quantized.getpalette()[:COLOURS * 3]
    palette += [0] * (COLOURS * 3 - len(palette))
    tables = []
    for index in range(len(small)):
        codes = [quantized.getpixel((index * width + x, y)) + 1 if shown.getpixel((index * width + x, y)) else 0
                 for y in range(height) for x in range(width)]
        codes += [0] * (-len(codes) % 8)
        tables.append([sum(codes[at + shift] << (4 * shift) for shift in range(8)) for at in range(0, len(codes), 8)])
    return [tuple(value / 255 for value in palette[i:i + 3]) for i in range(0, len(palette), 3)], tables


def main():
    lines = [
        "// Generated by tools/launcher/bake-loading-sprite.py from headless/prosperoeden/ui/art.",
        "// Do not edit: change the pictures or the script and run it again.",
    ]
    colours, sizes, palettes, tables = [], [], [], []
    frame = 0
    for set_index, (name, (names, width, height)) in enumerate(SETS.items()):
        palette, words = bake(names, width, height)
        lines.append(f"const int k{name} = {frame}; // its first frame; {len(names)} frames: "
                     + ", ".join(names))
        colours += palette
        for table in words:
            sizes.append((width, height))
            palettes.append(set_index * COLOURS)
            tables.append(table)
        frame += len(names)
    lines += [
        "// Each frame's size in texels, and where its set's colours start in kSpriteColour: texel 0 is",
        "// transparent, texel n is kSpriteColour[kSpritePalette[frame] + n - 1].",
        f"const ivec2 kSpriteSize[{len(sizes)}] = ivec2[{len(sizes)}](" +
        ", ".join(f"ivec2({w}, {h})" for w, h in sizes) + ");",
        f"const int kSpritePalette[{len(palettes)}] = int[{len(palettes)}](" + ", ".join(map(str, palettes)) + ");",
        f"const vec3 kSpriteColour[{len(colours)}] = vec3[{len(colours)}](",
    ]
    for start in range(0, len(colours), 4):
        chunk = ", ".join(f"vec3({r:.3f}, {g:.3f}, {b:.3f})" for r, g, b in colours[start:start + 4])
        lines.append("    " + chunk + ("," if start + 4 < len(colours) else ""))
    lines.append(");")
    for index, table in enumerate(tables):
        lines.append(f"const uint kSprite{index}[{len(table)}] = uint[{len(table)}](")
        for start in range(0, len(table), 8):
            chunk = ", ".join(f"0x{value:08x}u" for value in table[start:start + 8])
            lines.append("    " + chunk + ("," if start + 8 < len(table) else ""))
        lines.append(");")
    lines += ["// One word of a frame.", "uint sprite_word(int frame, int word)", "{", "    switch (frame)", "    {"]
    lines += [f"    case {index}: return kSprite{index}[word];" for index in range(len(tables))]
    lines += ["    }", "    return 0u;", "}"]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUTPUT.name}: {len(tables)} frames in {len(SETS)} sets, {sum(map(len, tables))} words")


if __name__ == "__main__":
    main()
